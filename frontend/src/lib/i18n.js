function getValue(language, key) {
  return key.split(".").reduce((current, part) => {
    if (!current || typeof current !== "object") return undefined;
    return current[part];
  }, translations[language]);
}

function formatValue(value, replacements) {
  if (typeof value !== "string") return value;
  return Object.entries(replacements).reduce(
    (text, [placeholder, replacement]) =>
      text.replace(new RegExp(`{{${placeholder}}}`, "g"), replacement),
    value,
  );
}

export function t(key, language = "fa", replacements = {}) {
  const value = getValue(language, key) || getValue("fa", key) || key;
  return formatValue(value, replacements);
}

